# safety probe: what can a hostile script do inside the sandbox?
import os, subprocess, socket, sys
def t(label, fn):
    try: print('PROBE', label, '->', repr(fn())[:150])
    except Exception as e: print('PROBE', label, '-> BLOCKED', type(e).__name__, str(e)[:100])
t('net connect 1.1.1.1:80', lambda: socket.create_connection(('1.1.1.1', 80), timeout=3))
t('dns', lambda: socket.gethostbyname('example.com'))
t('read /opt', lambda: os.listdir('/opt'))
t('read /root', lambda: os.listdir('/root'))
t('read /tank', lambda: os.listdir('/tank'))
t('read /etc/shadow', lambda: open('/etc/shadow').read(10))
t('read /etc/nxeon-build', lambda: os.listdir('/etc/nxeon-build'))
t('write /etc/x', lambda: open('/etc/x','w').write('x'))
t('write /usr/x', lambda: open('/usr/x','w').write('x'))
t('write /tank/x', lambda: open('/tank/x','w').write('x'))
t('write cwd', lambda: open('probe_ok.txt','w').write('x'))
t('whoami/uid', lambda: (os.getuid(), os.getcwd()))
t('subprocess id', lambda: subprocess.run(['id'], capture_output=True, text=True).stdout)
t('subprocess curl', lambda: subprocess.run(['curl','-s','-m','3','http://example.com'], capture_output=True, text=True))
t('env keys', lambda: sorted(os.environ.keys()))
t('/proc other pid env', lambda: open('/proc/1/environ').read(20))
t('ls /var/lib', lambda: os.listdir('/var/lib'))
t('ls /home /mnt', lambda: (os.listdir('/home'), os.listdir('/mnt')))
t('bpy.ops.wm.url_open', lambda: __import__('bpy').ops.wm.url_open(url='http://example.com'))
